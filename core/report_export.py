"""Report export - Markdown format"""
import json
from datetime import datetime


def export_run_markdown(run: dict, results: list, score=None) -> str:
    """Export a single test run as a Markdown report"""
    lines = []
    ts = run.get("started_at", "")
    try:
        dt = datetime.fromisoformat(ts)
        ts = dt.strftime("%Y-%m-%d %H:%M:%S")
    except Exception:
        pass

    lines.append(f"# MCP Server Evaluation Report")
    lines.append("")
    lines.append(f"**Server**: {run['server_name']}")
    lines.append(f"**Run ID**: #{run['id']}")
    lines.append(f"**Time**: {ts}")
    lines.append(f"**Suite**: {run['suite_type']}")
    lines.append(f"**Status**: {run['status']}")
    lines.append(f"**Cases Passed**: {run['passed']}/{run['total_cases']}")
    if run.get("duration_sec"):
        lines.append(f"**Total Duration**: {run['duration_sec']:.1f}s")

    if score:
        lines.append("")
        lines.append("## Overall Grade")
        lines.append("")
        lines.append(f"| Dimension | Score |")
        lines.append(f"|-----------|-------|")
        lines.append(f"| **Overall** | **{score.letter} ({score.overall:.0f}/100)** |")
        lines.append(f"| Functional | {score.functional:.0f}% |")
        lines.append(f"| Performance | {score.performance:.0f}% |")
        lines.append(f"| Security | {score.security:.0f}% |")
        lines.append("")
        lines.append(f"> {score.summary}")

    lines.append("")
    lines.append("## Detailed Results")
    lines.append("")
    lines.append("| ID | Case | Category | Status | Duration | Note |")
    lines.append("|----|------|----------|--------|----------|------|")
    icons = {"passed": "✅", "failed": "❌", "skipped": "⏭️", "error": "💥"}
    for r in results:
        icon = icons.get(r["status"], "❓")
        dur = f"{r['duration_ms']:.0f}ms"
        note = (r.get("error_msg") or "").replace("|", "\\|").replace("\n", " ")[:60]
        lines.append(f"| {r['case_id']} | {r['case_name']} | {r['category']} | {icon} {r['status']} | {dur} | {note} |")

    # Performance summary
    perf = [r for r in results if r["category"] == "performance" and r["status"] == "passed"]
    if perf:
        lines.append("")
        lines.append("## Performance Summary")
        lines.append("")
        for r in perf:
            try:
                d = json.loads(r["detail_json"]) if r.get("detail_json") else {}
            except Exception:
                continue
            lines.append(f"**{r['case_id']} {r['case_name']}**")
            if "mean_ms" in d:
                lines.append(f"- mean: {d['mean_ms']}ms / p50: {d.get('p50_ms', '-')}ms / p95: {d.get('p95_ms', '-')}ms / p99: {d.get('p99_ms', '-')}ms")
                if "max_min_ratio" in d:
                    lines.append(f"- stability: {d.get('trend', '-')} (max/min = {d['max_min_ratio']:.1f})")
            if "concurrency_results" in d:
                for cr in d["concurrency_results"]:
                    lines.append(f"- concurrency {cr['concurrency']}: {cr['rps']:.1f} RPS / p50 {cr['p50_ms']}ms / errors {cr['errors']}")
            lines.append("")

    lines.append("")
    lines.append("---")
    lines.append(f"*Generated by MCP Evaluation Platform at {datetime.now().strftime('%Y-%m-%d %H:%M')}*")
    return "\n".join(lines)
